// Generates lib/src/case_data.dart: JavaScript toUpperCase / toLowerCase for every
// code point they change. Dart's own case mapping is simpler (for example it keeps
// "ß" in upper case), so the port uses these tables to match the JavaScript reference.
// Usage: node tool/build_case_data.mjs
import { writeFileSync } from 'node:fs';

function caseMap(fn) {
  const out = [];
  for (let cp = 0; cp < 0x110000; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    const m = fn(s);
    if (m !== s) out.push(`  0x${cp.toString(16).toUpperCase()}: [${[...m].map((c) => `0x${c.codePointAt(0).toString(16).toUpperCase()}`).join(', ')}],`);
  }
  return out.join('\n');
}

writeFileSync(new URL('../lib/src/case_data.dart', import.meta.url), `// Generated by tool/build_case_data.mjs from the JavaScript engine (Node ${process.versions.node},
// Unicode ${process.versions.unicode}). Do not edit.

/// String.prototype.toUpperCase for every code point it changes.
const Map<int, List<int>> upperMap = {
${caseMap((s) => s.toUpperCase())}
};

/// String.prototype.toLowerCase for every code point it changes (context-free).
const Map<int, List<int>> lowerMap = {
${caseMap((s) => s.toLowerCase())}
};
`);
console.log('Wrote lib/src/case_data.dart');
